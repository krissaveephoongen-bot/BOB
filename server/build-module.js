// Rebuilds modules/index.js from the prototype's rules, so the browser prototype and the server share one rule set.
// Run: node build-module.js   (then: docker compose restart nakama)
const fs = require('fs'), path = require('path');
const src = fs.readFileSync(path.join(__dirname, '../prototype/index.html'), 'utf8');
const a = src.indexOf('const STATS='), b = src.indexOf('/* ============ STATE ============ */');
if (a < 0 || b < 0) throw new Error('rule markers not found in prototype/index.html');
const head = '// GENERATED by server/build-module.js from prototype/index.html. Do not edit by hand.\n' +
  '// Battle of the Brooms: server-authoritative rules. The server, not the phone, computes every score.\n';
const tail = fs.readFileSync(path.join(__dirname, 'rpc.js'), 'utf8') + fs.readFileSync(path.join(__dirname, 'analytics.js'), 'utf8') +
  fs.readFileSync(path.join(__dirname, 'match.js'), 'utf8');
fs.writeFileSync(path.join(__dirname, 'modules/index.js'), head + src.slice(a, b) + tail);
console.log('wrote modules/index.js');
